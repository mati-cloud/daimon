/// First-launch configurator. Idempotent — safe to re-run from command palette.
/// Writes ~/.config/daimon/config.zsh, which puts the daimon CLI on PATH.
pub fn run() -> anyhow::Result<()> {
    let config_dir = dirs::home_dir()
        .map(|h| h.join(".config").join("daimon"))
        .ok_or_else(|| anyhow::anyhow!("cannot determine home dir"))?;

    std::fs::create_dir_all(&config_dir)?;

    // Add the directory containing this binary to PATH so `daimon` is always findable.
    let bin_dir = std::env::current_exe()
        .ok()
        .and_then(|p| p.parent().map(|d| d.to_path_buf()));

    let mut lines: Vec<String> = vec![
        "# daimon config — generated by `daimon setup`, safe to edit".into(),
        "# Re-run setup: open command palette → daimon setup".into(),
        String::new(),
    ];

    if let Some(dir) = bin_dir {
        lines.push("# daimon CLI on PATH".into());
        lines.push(format!("export PATH=\"{}:$PATH\"", dir.display()));
        lines.push(String::new());
    }

    let config_path = config_dir.join("config.zsh");
    std::fs::write(&config_path, lines.join("\n"))?;
    eprintln!("wrote {}", config_path.display());

    // Ensure ~/.zshrc sources config.zsh
    let zshrc = dirs::home_dir().map(|h| h.join(".zshrc"));
    if let Some(zshrc) = zshrc {
        let source_line = format!("source ~/.config/daimon/config.zsh");
        let existing = std::fs::read_to_string(&zshrc).unwrap_or_default();
        if !existing.contains(&source_line) {
            let append = format!("\n# daimon\n{}\n", source_line);
            std::fs::write(&zshrc, format!("{}{}", existing.trim_end(), append))?;
            eprintln!("added source line to {}", zshrc.display());
            eprintln!("run: source ~/.zshrc");
        }
    }

    Ok(())
}
